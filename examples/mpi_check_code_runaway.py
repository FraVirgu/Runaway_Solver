#!/usr/bin/env python3
#
# MPI check of DREAM's physics test code_runaway (Dreicer runaway rate vs
# CODE), run with the parallel dreami in kinetic-only mode.
#
# code_runaway prescribes the whole background (E, T_cold, n_cold, fully
# ionised ions) and has no avalanche, so f_hot depends on the background
# only. dreami is therefore run with -dream_kinetic_only (f_hot alone in the
# matrix, solved with AMG), and the fluid quantity the test checks is
# computed afterwards from f_hot:
#
#   runaway rate = d n_re/dt = - d/dt integral(f_hot d^3p)
#
# f_hot only loses particles through p_max (BC_PHI_CONST, no particle
# source since S_particle = 0), and n_re in the full run counts exactly the
# particles that left, so this is the rate the test takes from n_re
# (Delta n_re / Delta t over the last time step).
#
# For every (T, E) point of the test and every number of ranks in NPROCS,
# the script checks
#
#   1. CODE       rate on 1 rank vs CODE, with the test's 5 % tolerance
#   2. parallel   run on P ranks vs 1 rank: f_hot and the rate
#
# The rate is a small difference of two large densities, so it is only
# resolved when the particles leaving in a time step are well above the
# solver tolerance (AMG rtol 1e-10): points where they are below MINREL of
# the density are reported, not checked against CODE.
#
# The settings are generated by the test's own gensettings(), with three
# changes: kinetic-only mode, the AMG linear solver with diagonal scaling
# (-dream_scale diag), and the TCDF flux limiter for the advection
# interpolation instead of QUICK. QUICK gives a matrix on which AMG does not
# converge (nor does it with SMART or MUSCL); plain upwind converges but its
# numerical diffusion puts the rate several times above CODE. TCDF
# converges and stays within the test's 5 % (also DREAM_avalanche uses it).
# At T >= HIGHT the test's Np = 100 is too coarse for TCDF (+6 % at 5 keV,
# +11 % at 10 keV), so these points use Np = NP_HIGHT (200: -1 %, -2 %);
# the colder points keep Np = 100, since there AMG does not converge on
# the finer grid.
#
# Run as
#
#   $ ./mpi_check_code_runaway.py                         # NPROCS="1 2 4", mpirun
#   $ NPROCS="1 4 8" POINTS=all ./mpi_check_code_runaway.py
#   $ MPIRUN="srun -n" NPROCS="1 16" sbatch -n 16 --wrap="python mpi_check_code_runaway.py"
#
# Environment:
#   DREAM_ROOT  DREAM tree (default: DREAM next to Runaway_Solver)
#   NPROCS      ranks to run with; the first one must be 1 (default "1 2 4")
#   MPIRUN      launcher, followed by the number of ranks (default "mpirun -n")
#   POINTS      "all", or (iE,iT) pairs as "0,4 3,0" (default: one point per T)
#   FTOL        tolerance on max|f_P - f_1| / max|f_1| (default 1e-6)
#   RTOL        tolerance on the relative rate difference P vs 1 (default 1e-3)
#   MINREL      smallest resolved rate*dt/density (default 1e-6)
#   HIGHT       temperature [eV] from which NP_HIGHT is used (default 5000)
#   NP_HIGHT    number of momentum cells at T >= HIGHT (default 200)
#   OUTDIR      working directory (default ./mpi_check_code_runaway)
#
# ###################################################################

import os
import subprocess
import sys
import numpy as np

DREAM_ROOT = os.path.expanduser(os.environ.get(
    'DREAM_ROOT', os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'DREAM')))
TESTDIR = os.path.join(DREAM_ROOT, 'tests', 'physics')

sys.path.append(os.path.join(DREAM_ROOT, 'py'))
sys.path.append(TESTDIR)                                    # 'dreamtests'
sys.path.append(os.path.join(TESTDIR, 'code_runaway'))

from DREAM.DREAMOutput import DREAMOutput
import DREAM.Settings.Equations.HotElectronDistribution as FHot
import DREAM.Settings.Solver as Solver
import code_runaway

DREAMI = os.path.join(DREAM_ROOT, 'build', 'iface', 'dreami')
NPROCS = [int(p) for p in os.environ.get('NPROCS', '1 2 4').split()]
MPIRUN = os.environ.get('MPIRUN', 'mpirun -n').split()
FTOL = float(os.environ.get('FTOL', 1e-6))
RTOL = float(os.environ.get('RTOL', 1e-3))
MINREL = float(os.environ.get('MINREL', 1e-6))
HIGHT = float(os.environ.get('HIGHT', 5000))
NP_HIGHT = int(os.environ.get('NP_HIGHT', 200))
OUTDIR = os.path.abspath(os.environ.get('OUTDIR', 'mpi_check_code_runaway'))

# Tolerance of the test itself, against CODE
CODE_TOLERANCE = 5e-2

if NPROCS[0] != 1:
    sys.exit('NPROCS must start with 1 (the serial reference).')

T, E, CODErr = code_runaway.loadCODE(os.path.join(TESTDIR, 'code_runaway', 'CODE-rates.mat'))
nE, nT = T.shape

pts = os.environ.get('POINTS', '')
if pts == 'all':
    POINTS = [(i, j) for i in range(nE) for j in range(nT)]
elif pts:
    POINTS = [tuple(int(k) for k in p.split(',')) for p in pts.split()]
else:
    # one point per temperature, at the largest E (the largest, best
    # resolved runaway rate of that column)
    POINTS = [(nE-1, j) for j in range(nT)]


def run_case(i, j, nprocs):
    """
    Generate the test's settings for point (i, j), run them kinetic-only on
    'nprocs' ranks and return (f_hot, runaway rate, rate*dt/density), or
    None if dreami failed.
    """
    tag = f'E{i}_T{j}_np{nprocs}'

    ds = code_runaway.gensettings(T=T[i,j], E=E[i,j])
    ds.eqsys.f_hot.setAdvectionInterpolationMethod(ad_int=FHot.AD_INTERP_TCDF)
    if T[i,j] >= HIGHT:
        ds.hottailgrid.setNp(NP_HIGHT)
    ds.solver.setLinearSolver(Solver.LINEAR_SOLVER_AMG)
    ds.output.setFilename(f'output_{tag}.h5')
    ds.save(os.path.join(OUTDIR, f'settings_{tag}.h5'))

    # dreami does not pass its command line to PETSc: options go through
    # PETSC_OPTIONS
    env = dict(os.environ)
    env['PETSC_OPTIONS'] = env.get('PETSC_OPTIONS', '') + ' -dream_kinetic_only -dream_scale diag'

    log = os.path.join(OUTDIR, f'log_{tag}.txt')
    with open(log, 'w') as fh:
        subprocess.run(MPIRUN + [str(nprocs), DREAMI, f'settings_{tag}.h5'],
                       cwd=OUTDIR, env=env, stdout=fh, stderr=subprocess.STDOUT)

    # dreami can exit with 0 after a failed time step; it then writes no output
    outfile = os.path.join(OUTDIR, f'output_{tag}.h5')
    if not os.path.isfile(outfile):
        print(f'    np {nprocs:2d}   dreami FAILED, see {log}')
        return None

    do = DREAMOutput(outfile)
    f = np.array(do.eqsys.f_hot.data)
    n = do.eqsys.f_hot.density()[:,0]          # integral(f_hot d^3p), per time
    t = np.array(do.grid.t)
    do.close()

    # rate over the last time step, as the test takes it from n_re
    rr = -(n[-1] - n[-2]) / (t[-1] - t[-2])
    return f, rr, abs(n[-1] - n[-2]) / n[-2]


def main():
    os.makedirs(OUTDIR, exist_ok=True)
    print(f'dreami     {DREAMI}   (-dream_kinetic_only -dream_scale diag, AMG, TCDF)')
    print(f'ranks      {NPROCS}   ({" ".join(MPIRUN)} <n>)')
    print(f'tolerance  f_hot {FTOL:.0e}, rate {RTOL:.0e} (vs 1 rank), {CODE_TOLERANCE:.0%} (vs CODE)')
    print(f'output     {OUTDIR}\n')

    success = True
    for i, j in POINTS:
        print(f'T = {T[i,j]:g} eV, E = {E[i,j]:.4f} V/m   (CODE rate {CODErr[i,j]:.3e})')

        ref = run_case(i, j, 1)
        if ref is None:
            success = False
            print()
            continue
        fref, rref, relref = ref
        resolved = relref >= MINREL

        # 1. rate on 1 rank vs CODE, as in the test
        if resolved:
            Delta = abs(rref / CODErr[i,j] - 1.0)
            ok = Delta <= CODE_TOLERANCE
            success &= ok
            print(f'    CODE    np  1   rate {rref:.4e}   Delta {Delta*100:7.3f} %   {"ok" if ok else "FAIL"}')
        else:
            print(f'    CODE    np  1   rate not resolved (density change per step {relref:.1e} < {MINREL:.0e}), skipped')

        # 2. P ranks vs 1 rank
        for P in NPROCS[1:]:
            res = run_case(i, j, P)
            if res is None:
                success = False
                continue
            df = np.max(np.abs(res[0] - fref)) / np.max(np.abs(fref))
            dr = abs(res[1] - rref) / abs(rref) if rref != 0 else abs(res[1])
            ok = df <= FTOL and (dr <= RTOL or not resolved)
            success &= ok
            print(f'    MPI     np {P:2d}   f_hot {df:.2e}   rate {res[1]:.4e} ({dr:.2e})   {"ok" if ok else "FAIL"}')
        print()

    print('ALL CHECKS PASSED' if success else 'SOME CHECKS FAILED')
    return 0 if success else 1


if __name__ == '__main__':
    sys.exit(main())
